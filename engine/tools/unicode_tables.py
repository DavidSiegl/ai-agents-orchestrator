"""Write engine/src/py/unicode_tables.rs: the character classes of Python's str methods and re that the engine's
port of orchestrator.py needs, as ranges of code points, from the Python that runs it (`uv run python
engine/tools/unicode_tables.py`). Run it again when .python-version moves to a Python with a newer Unicode
database, and commit the result with the change."""

import sys
import textwrap
import unicodedata

OUT = "engine/src/py/unicode_tables.rs"


def ranges(test) -> list[tuple[int, int]]:
    """The inclusive ranges of the code points, surrogates aside, for which test(chr(c)) is true."""
    out: list[tuple[int, int]] = []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF or not test(chr(c)):
            continue
        if out and out[-1][1] == c - 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


def table(name: str, doc: str, test) -> str:
    """A Rust constant name of the ranges test holds for, under doc as its comment."""
    rows = ranges(test)
    body = "".join(f"    ({lo:#x}, {hi:#x}),\n" for lo, hi in rows)
    lines = "".join(f"/// {line}\n" for line in textwrap.wrap(doc, 116))
    return f"{lines}pub(crate) const {name}: &[(u32, u32)] = &[\n{body}];\n"


def main() -> None:
    """Write the tables to OUT."""
    parts = [
        ("// Generated by engine/tools/unicode_tables.py from Python "
         f"{sys.version_info.major}.{sys.version_info.minor}'s Unicode {unicodedata.unidata_version}; do not edit.\n"),
        table("DECIMAL", "The characters of str.isdecimal and of re's `\\d`. Each range is runs of the digits 0 to 9, "
              "so a digit's value is its distance from the range's start, modulo 10.", str.isdecimal),
        table("SPACE", "The characters of str.isspace, which str.strip and re's `\\s` take as blanks.", str.isspace),
        table("ALNUM", "The characters of str.isalnum, which re's `\\w` takes with `_`.", str.isalnum),
        table("PRINTABLE", "The characters of str.isprintable, which repr() writes as they are.", str.isprintable),
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
